/**
 * THE MENU STAGE AT REST (2026-11-03) — and the generator of the table it rests on.
 *
 * The stage draws a staged world it never steps, so BIOBUZZ moves its hive and flower elements to
 * where a match's 3D physics leaves them (`menuRest.ts`). Those poses are baked into
 * `menuRest.gen.ts` by this file:
 *
 *   npx tsx scripts/smoke-biobuzz/menuStage.ts --write
 *
 * Run it after anything that moves where a staged element comes to rest (staging, the hive or
 * flower colliders, the 3D contact model): the first check below fails until you do.
 */

const GEN = 'src/games/biobuzz/menuRest.gen.ts';
/** 6 s. Measured: every element is within 0.002 in of its final pose by tick 300. */
const SETTLE_TICKS = 360;
/** the last ticks a settled element may not move in */
const STILL_TICKS = 60;

/** the stage's world, as `MenuStage.tsx` builds it for the 3D stage */
function stageWorld(robot: boolean): World {
  const w = createBiobuzzWorld('match', STAGE_SEED, robot ? [setup(0, 'blue')] : [], undefined, '3d');
  const r = w.robots[0];
  if (r) {
    r.pos = { x: SHOW.x, y: SHOW.y };
    r.heading = SHOW.heading;
  }
  return w;
}

const placed = (w: World): Artifact[] => w.balls.filter((b) => b.state.kind === 'element');

/** the stage's world stepped by the real 3D pipeline until it is still */
function settle(robot: boolean): { world: World; moved: number; speed: number } {
  const w = stageWorld(robot);
  const cmds = new Map();
  let mark = new Map<number, Artifact>();
  for (let t = 0; t < SETTLE_TICKS; t++) {
    if (t === SETTLE_TICKS - STILL_TICKS) mark = new Map(placed(w).map((b) => [b.id, structuredClone(b)]));
    step3d(w, SIM_DT, cmds);
  }
  let moved = 0;
  let speed = 0;
  for (const b of placed(w)) {
    const m = mark.get(b.id);
    if (m) moved = Math.max(moved, Math.hypot(b.pos.x - m.pos.x, b.pos.y - m.pos.y, b.z - m.z));
    speed = Math.max(speed, Math.hypot(b.vel.x, b.vel.y, b.vz));
  }
  return { world: w, moved, speed };
}

const round3 = (n: number): number => Math.round(n * 1000) / 1000;

function restRows(w: World): MenuRestPose[] {
  const rows: MenuRestPose[] = [];
  for (const b of placed(w)) {
    if (b.state.kind !== 'element') continue;
    rows.push({ el: b.state.el, slot: b.state.slot, x: round3(b.pos.x), y: round3(b.pos.y), z: round3(b.z) });
  }
  return rows.sort((p, q) => (p.el < q.el ? -1 : p.el > q.el ? 1 : p.slot - q.slot));
}

function genSource(rows: readonly MenuRestPose[]): string {
  const body = rows
    .map((p) => `  { el: '${p.el}', slot: ${p.slot}, x: ${p.x}, y: ${p.y}, z: ${p.z} },`)
    .join('\n');
  return `// GENERATED by \`npx tsx scripts/smoke-biobuzz/menuStage.ts --write\` — DO NOT HAND-EDIT.
//
// Where the real 3D physics leaves each staged HIVE and FLOWER element: the menu stage's world
// (STAGE_SEED, '3d') stepped ${SETTLE_TICKS / 60} s by \`step3d\`. Read by \`menuRest.ts\`. \`z\` is the element's
// underside, the 3D convention. Inches, rounded to 1e-3.

export interface MenuRestPose {
  el: string;
  slot: number;
  x: number;
  y: number;
  z: number;
}

export const BB_MENU_REST: readonly MenuRestPose[] = [
${body}
];
`;
}

/** the gap between an up-cell element's underside and its cell floor, in the tray's frame, and
 * whether the sim counts it as in the cell (`insideCell`, the membership test `derive.ts` uses) */
function cellSeat(w: World, b: Artifact, a: Alliance): { gap: number; inside: boolean } {
  const r = b.r ?? 0;
  const theta = hiveTiltAngle(w, a);
  const side = w.biobuzz!.hives[a].up === 'north' ? 1 : -1;
  const box = hiveCellLocalBox(side, a);
  const { b: wl } = rotate2(b.pos.y, b.z + r - BB3_HIVE_PIVOT_Z, -theta);
  return { gap: wl - r - box.wMin, inside: insideCell(b.pos.x, b.pos.y, b.z + r, a, side, theta) };
}

export function menuStageChecks(check: Check): void {
  // ── the table is the physics ────────────────────────────────────────────────────────────────
  const fresh = settle(false);
  const want = restRows(fresh.world);
  let drift = 0;
  let missing = 0;
  for (const p of want) {
    const q = BB_MENU_REST.find((r) => r.el === p.el && r.slot === p.slot);
    if (!q) missing++;
    else drift = Math.max(drift, Math.hypot(p.x - q.x, p.y - q.y, p.z - q.z));
  }
  check(
    'STAGE: menuRest.gen.ts matches a fresh 3D settle of the stage world (else re-run `npx tsx scripts/smoke-biobuzz/menuStage.ts --write`)',
    missing === 0 && BB_MENU_REST.length === want.length && drift <= 0.05,
    `rows ${BB_MENU_REST.length}/${want.length}, missing ${missing}, max drift ${drift.toFixed(4)} in`,
  );
  check(
    'STAGE: 22 elements are baked: four POLLEN in each of four FLOWERS, three NECTAR in each up-CELL',
    want.length === 22 && want.filter((p) => p.el.startsWith('flower:')).length === 16,
    String(want.length),
  );
  check(
    `STAGE: the settle is at rest, not caught mid-fall (moved ≤ 0.01 in over its last ${STILL_TICKS} ticks)`,
    fresh.moved <= 0.01 && fresh.speed <= BB3_REST_SPEED,
    `moved ${fresh.moved.toFixed(4)} in, speed ${fresh.speed.toFixed(3)} in/s`,
  );
  // the stage keeps its HIVES at the staged tilt, so the settle must not have swung them
  const tilt = (['red', 'blue'] as const).map((a) =>
    Math.abs(hiveTiltAngle(fresh.world, a) - hiveTiltAngle(stageWorld(false), a)),
  );
  check('STAGE: the settle leaves both HIVES at their staged tilt', Math.max(...tilt) <= 1e-3, tilt.map((t) => t.toFixed(5)).join(' '));
  // the table ignores the player's robot, which stands at SHOW, clear of every hive and flower
  const withRobot = restRows(settle(true).world);
  let robotDiff = 0;
  for (const p of withRobot) {
    const q = want.find((r) => r.el === p.el && r.slot === p.slot);
    robotDiff = Math.max(robotDiff, q ? Math.hypot(p.x - q.x, p.y - q.y, p.z - q.z) : Infinity);
  }
  check('STAGE: the robot at SHOW does not change where any element comes to rest', robotDiff <= 0.01, `${robotDiff.toFixed(5)} in`);

  // ── the stage's world, rested, as the module rests it ─────────────────────────────────────
  const rest = moduleFor('biobuzz').restMenuWorld;
  check('STAGE: BIOBUZZ fills GameModule.restMenuWorld', typeof rest === 'function');
  if (typeof rest !== 'function') return;
  const staged = stageWorld(true);
  const w = stageWorld(true);
  const bagBefore = JSON.stringify(w.biobuzz);
  rest(w);

  const seats = placed(w)
    .filter((b) => b.state.kind === 'element' && b.state.el.startsWith('hive:'))
    .map((b) => ({ b, ...cellSeat(w, b, b.state.kind === 'element' && b.state.el === 'hive:red' ? 'red' : 'blue') }));
  const stagedGap = Math.min(
    ...placed(staged)
      .filter((b) => b.state.kind === 'element' && b.state.el.startsWith('hive:'))
      .map((b) => cellSeat(staged, b, b.state.kind === 'element' && b.state.el === 'hive:red' ? 'red' : 'blue').gap),
  );
  check(
    'STAGE: every up-CELL NECTAR rests on its cell floor (underside within 0.1 in), not at the staged mid-opening',
    seats.length === 6 && seats.every((s) => Math.abs(s.gap) <= 0.1),
    `gaps ${seats.map((s) => s.gap.toFixed(3)).join(' ')} (staged ${stagedGap.toFixed(2)})`,
  );
  check("STAGE: every up-CELL NECTAR is in its cell by the sim's own membership test", seats.every((s) => s.inside));

  for (let i = 0; i < 4; i++) {
    const col = placed(w)
      .filter((b) => b.state.kind === 'element' && b.state.el === `flower:${i}`)
      .sort((p, q) => (p.state.kind === 'element' && q.state.kind === 'element' ? p.state.slot - q.state.slot : 0));
    let contact = 0;
    let lean = 0;
    for (let k = 1; k < col.length; k++) {
      const [p, q] = [col[k - 1], col[k]];
      const d = Math.hypot(q.pos.x - p.pos.x, q.pos.y - p.pos.y, q.z + (q.r ?? 0) - (p.z + (p.r ?? 0)));
      contact = Math.max(contact, Math.abs(d - (p.r ?? 0) - (q.r ?? 0)));
      lean = Math.max(lean, Math.hypot(q.pos.x - p.pos.x, q.pos.y - p.pos.y));
    }
    check(
      `STAGE: FLOWER ${i}'s four POLLEN each rest on the one below (centres a diameter apart, ±0.15 in) and lean off a straight column (a step ≥ 0.5 in; staging scatters at most 0.32)`,
      col.length === 4 && contact <= 0.15 && lean >= 0.5,
      `contact error ${contact.toFixed(3)} in, largest step ${lean.toFixed(3)} in`,
    );
  }
  check('STAGE: resting moves positions only: the CELL contents and FLOWER stacks are unchanged', JSON.stringify(w.biobuzz) === bagBefore);
  check(
    'STAGE: resting leaves every other ball (garden, preloads, stock) where staging put it',
    w.balls.every((b, n) => b.state.kind === 'element' || JSON.stringify(b) === JSON.stringify(staged.balls[n])),
  );
  const flat = createBiobuzzWorld('match', STAGE_SEED, [setup(0, 'blue')]);
  const flatBefore = JSON.stringify(flat);
  rest(flat);
  check('STAGE: a 2D-physics world is left exactly as staged', JSON.stringify(flat) === flatBefore);

  const src = readFileSync('src/ui/MenuStage.tsx', 'utf8');
  check(
    'STAGE: MenuStage builds its world from STAGE_SEED and rests it through the module',
    /createWorld\('match', STAGE_SEED,/.test(src) && /\.restMenuWorld\?\.\(w\)/.test(src),
  );
}

// `npx tsx scripts/smoke-biobuzz/menuStage.ts --write` regenerates the table
if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href && process.argv.includes('--write')) {
  await initPhysics();
  await initPhysics3d();
  const rows = restRows(settle(false).world);
  writeFileSync(GEN, genSource(rows));
  console.log(`[menuStage] wrote ${rows.length} rest poses to ${GEN}`);
}
